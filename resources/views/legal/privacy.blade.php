<x-legal title="Privacy Policy">
    <div>
        <p>This explains what PhishCore collects, why, who else sees it, and the choices you have. PhishCore is a student project from Politeknik Brunei, and we have tried to collect as little as we can.</p>
    </div>

    <div>
        <h2>1. What we collect</h2>
        <ul>
            <li><strong class="text-white">Account details:</strong> your name, email address and a hashed password, plus an optional profile photo.</li>
            <li><strong class="text-white">What you scan:</strong> the link, sender address, message text, phone number or screenshot you submit, and the results (verdict, risk score, checks and date). Screenshots you upload are stored on our server.</li>
            <li><strong class="text-white">Site information found during a scan:</strong> for example a site's IP address and hosting details. This is about the site you checked, not about you.</li>
            <li><strong class="text-white">Sign-in sessions:</strong> a record of your devices (browser and system type) so Settings can show where you are signed in.</li>
            <li><strong class="text-white">Activity in the app:</strong> your Phish Lab progress, notifications and any investigation requests you make.</li>
            <li><strong class="text-white">AI chat messages:</strong> what you type to the chat adviser, only while you use it.</li>
        </ul>
    </div>

    <div>
        <h2>2. How we use it</h2>
        <ul>
            <li>To run scans, show your history and analytics, and let you export them.</li>
            <li>To keep the service secure, apply limits and prevent abuse.</li>
            <li>To send account emails such as password resets.</li>
            <li>To build the public threat feed from scans judged Suspicious or Phishing.</li>
            <li>To measure and improve detection for our project evaluation, using results and not your identity.</li>
        </ul>
        <p class="mt-2">We do not sell your data and we do not show advertising.</p>
    </div>

    <div>
        <h2>3. Who else receives data</h2>
        <p>To do their job, some outside services receive part of what you submit:</p>
        <ul>
            <li><strong class="text-white">Google Safe Browsing and VirusTotal</strong> receive the links you scan.</li>
            <li><strong class="text-white">An OCR service</strong> receives screenshots so the text in them can be read.</li>
            <li><strong class="text-white">AI providers</strong> (Google Gemini for the optional AI text check, and Groq for the chat adviser) receive the message text or chat messages when those features are switched on.</li>
            <li><strong class="text-white">Domain lookup and IP information services</strong> receive the domain or address being checked.</li>
            <li><strong class="text-white">Brevo</strong> delivers our emails, so it receives your email address and the message.</li>
            <li><strong class="text-white">Our hosting provider</strong> (DigitalOcean) stores the data on our server.</li>
        </ul>
        <p class="mt-2">Please do not submit anything you are not comfortable having checked by these services, such as private messages with passwords or bank details.</p>
    </div>

    <div>
        <h2>4. What is public</h2>
        <p>Scans judged Suspicious or Phishing can appear on the public Threat Reports page and in the downloadable feed with the reported link, the date, a status and a username. Your name, email address and risk scores are not shown. A scan is shared by link only if you create a share link, and you can switch it off at any time.</p>
    </div>

    <div>
        <h2>5. How long we keep it, and deleting it</h2>
        <p>We keep your data while your account exists. When you delete your account from Settings, your account and your scans are deleted from our database. Copies already held by the outside services above, and entries that have already been included in public feed downloads, are outside our control.</p>
    </div>

    <div>
        <h2>6. Cookies</h2>
        <p>PhishCore uses only the cookies it needs to keep you signed in and to protect forms against forgery. We do not use advertising or tracking cookies.</p>
    </div>

    <div>
        <h2>7. Security</h2>
        <p>Passwords are stored hashed, traffic is meant to travel over HTTPS, and scan pages are private to their owner unless a share link is created. No system is perfectly secure, so please use a strong, unique password.</p>
    </div>

    <div>
        <h2>8. Your choices and contact</h2>
        <p>You can view and change your details, export your scan history, and delete your account from the app. To ask a question or request help with your data, email <a href="mailto:phishcorebn@gmail.com">phishcorebn@gmail.com</a>. If we change this policy we will update the date above.</p>
    </div>
